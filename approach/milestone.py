"""Record a milestone for the project diary.

    python -m approach.milestone stage0-02-turn-test --title "Aircraft respond to instructions" \\
        --scenarios turn_test --summary "One paragraph on what was built."

For each scenario this runs a session and saves, under diary/<date>-<slug>/:
the session log, the self-contained radar replay, and a screenshot of the final
frame. It records a video of each replay into media/<date>-<slug>/ (kept out of
git; published as GitHub release assets by scripts/publish_milestone.sh), appends
the scores to diary/scores.csv, and writes a diary entry draft. An existing entry
keeps its hand-written notes: only the section between the AUTO markers is replaced.
"""

from __future__ import annotations

import argparse
import csv
import json
import shutil
import subprocess
from datetime import date
from pathlib import Path

from approach.radar import replay
from approach.run import ROOT, code_version, run_scenario
from approach.scenarios import SCENARIOS

DIARY = ROOT / "diary"
MEDIA = ROOT / "media"
AUTO_START = "<!-- AUTO:START (regenerated by approach.milestone) -->"
AUTO_END = "<!-- AUTO:END -->"
SCORE_FIELDS = [
    "date", "milestone", "scenario", "controller", "code_version", "arrivals", "landed",
    "separation_losses", "wake_violations", "min_spacing_nm", "mean_spacing_nm", "track_miles_per_arrival",
    "instructions_per_arrival", "safety_blocks", "go_arounds", "stable_at_1000ft_pct",
]


def video_speed(duration: float) -> int:
    """Playback speed that gives a video of roughly 30-60 seconds."""
    for s in (1, 5, 10, 20, 30, 60, 120):
        if duration / s <= 60:
            return s
    return 120


def record(html: Path, video_webm: Path, shot: Path, speed: int) -> tuple[Path | None, str]:
    if not shutil.which("node"):
        return None, "node not found: no video recorded"
    res = subprocess.run(
        ["node", str(ROOT / "scripts" / "record_replay.cjs"), str(html), str(video_webm), str(shot), str(speed)],
        capture_output=True, text=True,
    )
    if res.returncode != 0:
        return None, "recording failed: " + (res.stderr.strip().splitlines() or ["?"])[-1]
    if shutil.which("ffmpeg"):
        mp4 = video_webm.with_suffix(".mp4")
        conv = subprocess.run(
            ["ffmpeg", "-y", "-loglevel", "error", "-i", str(video_webm), "-c:v", "libx264", "-pix_fmt", "yuv420p",
             "-crf", "23", "-movflags", "+faststart", str(mp4)],
            capture_output=True, text=True,
        )
        if conv.returncode == 0:
            video_webm.unlink(missing_ok=True)
            return mp4, "ok"
    return video_webm, "ok"


def score_row(day: str, slug: str, scenario: str, log) -> dict:
    s = log.scores or {}
    row = {"date": day, "milestone": slug, "scenario": scenario, "controller": log.meta.get("controller"),
           "code_version": log.meta.get("code_version")}
    for f in SCORE_FIELDS[5:]:
        row[f] = s.get(f, "")
    return row


def scores_line(log) -> str:
    s = log.scores or {}
    if not s:
        return "map only"
    parts = [f"landed {s.get('landed', 0)}/{s.get('arrivals', 0)}", f"separation losses {s.get('separation_losses', 0)}"]
    if s.get("min_spacing_nm") not in (None, ""):
        parts.append(f"closest spacing at the runway {s['min_spacing_nm']} NM")
    if s.get("safety_blocks"):
        parts.append(f"safety blocks {s['safety_blocks']}")
    parts.append(f"instructions {s.get('instructions', 0)}")
    return ", ".join(parts)


def write_entry(entry: Path, title: str, day: str, slug: str, summary: str, rows: list[dict]) -> None:
    auto = [AUTO_START, "", f"Milestone `{slug}` · {day} · code `{rows[0]['code'] if rows else code_version()}`", ""]
    auto += ["| Scenario | What it shows | Replay | Screenshot | Video | Scores |", "| --- | --- | --- | --- | --- | --- |"]
    for r in rows:
        video = f"`{r['video']}` (release asset)" if r["video"] else r["video_note"]
        auto.append(f"| `{r['scenario']}` | {r['title']} | [replay]({r['html']}) | ![]({r['shot']}) | {video} | {r['scores']} |" if r["shot"]
                    else f"| `{r['scenario']}` | {r['title']} | [replay]({r['html']}) | — | {video} | {r['scores']} |")
    auto += ["", "Open a replay file in a browser to watch it; it needs no server.", "", AUTO_END]
    auto_text = "\n".join(auto)
    if entry.exists():
        text = entry.read_text()
        if AUTO_START in text and AUTO_END in text:
            head, rest = text.split(AUTO_START, 1)
            tail = rest.split(AUTO_END, 1)[1]
            entry.write_text(head + auto_text + tail)
            return
    body = [
        f"# {title}", "", auto_text, "",
        "## What was built", "", summary or "_To write._", "",
        "## What went wrong and how it was fixed", "", "_To write._", "",
        "## Notes", "", "_Your own notes for the blog or video._", "",
    ]
    entry.write_text("\n".join(body))


def write_index() -> None:
    """diary/README.md: one line per milestone, newest first."""
    lines = [
        "# Project diary",
        "",
        "One entry per milestone, newest first. Each folder holds the diary entry, the radar replays",
        "(open them in a browser), screenshots and the session logs. Videos are attached to the GitHub",
        "release with the same name as the milestone. `scores.csv` collects every milestone's scores.",
        "",
        "| Date | Milestone | Entry |",
        "| --- | --- | --- |",
    ]
    for d in sorted((p for p in DIARY.iterdir() if p.is_dir()), reverse=True):
        entry = d / "README.md"
        if not entry.exists():
            continue
        title = entry.read_text().splitlines()[0].lstrip("# ").strip()
        day, slug = d.name[:10], d.name[11:]
        lines.append(f"| {day} | `{slug}` | [{title}]({d.name}/README.md) |")
    (DIARY / "README.md").write_text("\n".join(lines) + "\n")


def main(argv: list[str] | None = None) -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("slug", help="milestone name, e.g. stage0-02-turn-test")
    p.add_argument("--title", required=True)
    p.add_argument("--scenarios", required=True, help="comma-separated scenario names")
    p.add_argument("--summary", default="", help="what was built (Markdown)")
    p.add_argument("--date", default=date.today().isoformat())
    p.add_argument("--no-video", action="store_true")
    args = p.parse_args(argv)

    folder = f"{args.date}-{args.slug}"
    out, media = DIARY / folder, MEDIA / folder
    out.mkdir(parents=True, exist_ok=True)
    media.mkdir(parents=True, exist_ok=True)
    rows, csv_rows = [], []
    for name in [s.strip() for s in args.scenarios.split(",") if s.strip()]:
        scenario = SCENARIOS[name]
        print(f"[{name}] running")
        log = run_scenario(scenario, milestone=args.slug)
        log.save(out / f"{name}.json")
        html = replay.write(log, out / f"{name}.html")
        shot, video, note = out / f"{name}.png", None, "not recorded"
        if not args.no_video:
            print(f"[{name}] recording")
            video, note = record(html, media / f"{name}.webm", shot, video_speed(log.meta["duration"]))
        rows.append({
            "scenario": name, "title": scenario.title, "html": html.name,
            "shot": shot.name if shot.exists() else "", "video": video.name if video else "", "video_note": note,
            "scores": scores_line(log), "code": log.meta["code_version"],
        })
        csv_rows.append(score_row(args.date, args.slug, name, log))
        print(f"[{name}] {scores_line(log)} | video: {video or note}")

    scores_csv = DIARY / "scores.csv"
    new = not scores_csv.exists()
    with scores_csv.open("a", newline="") as f:
        w = csv.DictWriter(f, fieldnames=SCORE_FIELDS)
        if new:
            w.writeheader()
        w.writerows(csv_rows)
    write_entry(out / "README.md", args.title, args.date, args.slug, args.summary, rows)
    write_index()
    (media / "milestone.json").write_text(json.dumps({"slug": args.slug, "title": args.title, "folder": folder}))
    print(f"Diary entry: {out / 'README.md'}")


if __name__ == "__main__":
    main()
